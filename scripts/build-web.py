            og_image_alt=e["og_image_alt"],
            canonical=canonical,
            app_store=APP_STORE,
            title=e["title"],
            desc=e["desc"],
            kicker=e["kicker"],
            h1_sub=e["h1_sub"],
            tagline=e["tagline"],
            hero_alt=e["hero_alt"],
            hero_alt2=e["hero_alt2"],
            hero_alt3=e["hero_alt3"],
            free_note=e["free_note"],
            feat_h2=e["feat_h2"].replace("{z}", '<span class="jp">ぜんぶ</span>'),
