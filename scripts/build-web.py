            f4t=e["f4t"], f4d=e["f4d"],
            f5t=e["f5t"], f5d=e["f5d"],
            f6t=e["f6t"], f6d=e["f6d"],
            f7t=e["f7t"], f7d=e["f7d"],
            how_kicker=e["how_kicker"],
            how_title=e["how_title"],
            how_sub=e["how_sub"],
            how1t=e["how1t"], how1d=e["how1d"],
            how2t=e["how2t"], how2d=e["how2d"],
            how3t=e["how3t"], how3d=e["how3d"],
            quiz_badge=e["quiz_badge"],
            quiz_title=e["quiz_title"],
            quiz_sub=e["quiz_sub"],
            quiz_data=_json.dumps(quiz_words.get(code, quiz_words["en"]), ensure_ascii=False),
            quiz_i18n=_json.dumps(i18n, ensure_ascii=False),
            faq_kicker=e["faq_kicker"],
            faq_title=e["faq_title"],
